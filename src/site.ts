/** A social card image (og:image) in public/images/og/. */
export interface OgCard {
  /** Absolute image URL. */
  url: string
  /** Text alternative, for og:image:alt and twitter:image:alt. */
  alt: string
}

/**
 * Social card images, 1200x630, generated by scripts/og-cards/generate.mjs.
 * Keyed by top-level topic slug, plus 'default' for every other page.
 */
const OG_CARDS: Record<string, string> = {
  default: 'Scott Vercuski, Software & Solution Architect: architecture guides, documentation templates, and design patterns.',
  'solution-architecture': 'Solution Architecture by Scott Vercuski: a design checklist, 50 architecture documentation templates, and a worked example.',
  'software-design-patterns': 'Software Design Patterns & Anti-Patterns by Scott Vercuski.',
}

/** Size of every image in {@link OG_CARDS}. */
export const OG_CARD_SIZE = { width: 1200, height: 630 }

/**
 * Picks a page's social card: its top-level topic's card, if it has one,
 * else the default.
 *
 * @param path - Route path, e.g. '/topics/solution-architecture/design-checklist/'.
 */
export function ogCardFor (path: string): OgCard {
  const topic = /^\/topics\/([^/?#]+)/i.exec(path)?.[1]?.toLowerCase()
  const key = topic && topic in OG_CARDS ? topic : 'default'
  return { url: `${SITE_URL}/images/og/${key}.png`, alt: OG_CARDS[key] }
}

/**
 * Builds the canonical URL of a page. The live host redirects every page
 * URL to lowercase with a trailing slash ('/About' -> '/about/'), so that
 * is the canonical form.
 *
 * @param path - Route path, optionally with a query string or hash.
 * @returns The absolute, lowercase URL with a trailing slash.
 */
export function canonicalUrl (path: string): string {
  const normalized = path.split(/[?#]/)[0].toLowerCase().replace(/\/+$/, '')
  return `${SITE_URL}${normalized}/`
}
